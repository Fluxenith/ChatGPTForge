import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
const rows = readFileSync(new URL('scripts/i18n-translations.txt', root), 'utf8').replace(/^\uFEFF/, '').trim().split(/\r?\n/).map(line => line.split('|'));
const messages = {};
for (const row of rows) {
  if (row.length !== 5 || row.some(value => !value.trim())) throw Error('Invalid five-language row: ' + row[0]);
  // Source aliases let existing English and Traditional Chinese copy use the
  // same translation without translating arbitrary user-generated strings.
  messages[row[0]] ??= row;
  messages[row[1]] = row;
}
writeFileSync(new URL('src/i18n-messages.ts', root), '// Generated by scripts/generate-i18n.mjs. Edit scripts/i18n-translations.txt.\nexport const messages: Record<string, readonly string[]> = ' + JSON.stringify(messages, null, 2) + ';\n');
const source = readFileSync(new URL('src/i18n.ts', root), 'utf8');
const ast = ts.createSourceFile('i18n.ts', source, ts.ScriptTarget.Latest, true);
const installer = ast.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === 'installLanguage');
if (!installer) throw Error('Missing browser language installer');
const browser = ts.transpileModule(installer.getText(ast).replace('export ', ''), {compilerOptions: {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None}}).outputText.replace(/^\"use strict\";\s*/, '').trim();
writeFileSync(new URL('src/i18n-browser-source.ts', root), '// Generated by scripts/generate-i18n.mjs.\nexport const browserLanguageSource = ' + JSON.stringify(browser) + ';\n');
writeFileSync(new URL('browser-extension/language.js', root), '// Generated by scripts/generate-i18n.mjs.\nconst messages = ' + JSON.stringify(messages) + ';\n' + browser + '\nconst forgeLanguage = installLanguage(messages);\nforgeLanguage.mount(document.body);\n');
console.log(`Generated ${rows.length} five-language translations.`);

for (const [index, code] of ['zh_TW','en','zh_CN','ja','ko'].entries()) {
  const directory = new URL(`browser-extension/_locales/${code}/`, root);
  mkdirSync(directory, {recursive:true});
  writeFileSync(new URL('messages.json', directory), JSON.stringify({extensionSettings:{message:messages['ChatGPTForge continuation settings'][index]},extensionDescription:{message:messages['Continue locally journaled ChatGPTForge handoffs using your existing signed-in Chrome. No model API calls.'][index]}},null,2)+'\n');
}
